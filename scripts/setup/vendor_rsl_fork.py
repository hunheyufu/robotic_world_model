"""Re-vendor the RWM ``rsl_rl`` fork into ``source/mbrl/mbrl/rl/rsl_rl_fork``.

The fork is pinned to a commit of https://github.com/leggedrobotics/rsl_rl_rwm and is vendored so
the pre-migration runner/algorithm/policy ABI keeps working on Isaac Lab 3.x without replacing the
host's ``rsl_rl`` distribution.

The vendoring rewrites the fork's absolute ``rsl_rl.*`` imports into the project namespace
(``mbrl.rl.rsl_rl_fork.*``) so the two libraries can coexist in one process, copies the fork's BSD
license, applies the project's patch series from ``scripts/setup/rsl_fork_patches`` and writes a
``NOTICE.md`` that lists the applied patches.

Local changes are never lost silently:

* regeneration is refused while the destination exists, unless ``--force`` is given; the refusal
  lists the files whose content differs from a fresh vendoring (i.e. what would be overwritten);
* ``--check`` compares the current destination against a fresh vendoring and exits non-zero on any
  difference, so a hand edit or a stale patch series is detected instead of being overwritten;
* the destination is only replaced after the whole pipeline (rewrite, license, patches, byte
  compile) succeeded, so a failing patch leaves the existing tree untouched.

Usage::

    python scripts/setup/vendor_rsl_fork.py \
        --source <site-packages>/rsl_rl \
        --license-file <dist-info>/licenses/LICENSE \
        --dest source/mbrl/mbrl/rl/rsl_rl_fork --force
    python scripts/setup/vendor_rsl_fork.py --source ... --license-file ... --check
"""

from __future__ import annotations

import argparse
import difflib
import pathlib
import py_compile
import re
import shutil
import subprocess
import sys
import tempfile

DEFAULT_DEST = "source/mbrl/mbrl/rl/rsl_rl_fork"
DEFAULT_PATCHES = "scripts/setup/rsl_fork_patches"
PREFIX = "mbrl.rl.rsl_rl_fork"
PINNED_COMMIT = "18eebcdd7145284c8d5eed5d8ed1a4b96c649693"
UPSTREAM = "https://github.com/leggedrobotics/rsl_rl_rwm.git"
IMPORT_RE = re.compile(r"^(\s*)from rsl_rl(\.[A-Za-z0-9_.]*)? import (.*)$")
PLAIN_IMPORT_RE = re.compile(r"^(\s*)import rsl_rl\s*$")
LEFTOVER_IMPORT_RE = re.compile(r"^\s*(from|import)\s+rsl_rl(\.|\s|$)")

NOTICE_TEMPLATE = """# Vendored `rsl_rl` (RWM fork)

This directory is a copy of the RWM `rsl_rl` fork, vendored so that the pre-migration
runner/algorithm/policy ABI keeps working on Isaac Lab 3.x **without** replacing the `rsl_rl`
distribution that ships with Isaac Lab 3.x.

- Upstream: `{upstream}`
- Commit: `{commit}`
- Installed distribution it was taken from: `rsl-rl-lib 3.1.0`
- License: BSD-3-Clause (see `LICENSE`)

Generated by `scripts/setup/vendor_rsl_fork.py`; do not edit the vendored files by hand. Every
project change belongs in a patch file under `scripts/setup/rsl_fork_patches/` and is applied
automatically by the vendoring step.

## What changed relative to upstream

1. Every absolute `rsl_rl.*` import was rewritten to `mbrl.rl.rsl_rl_fork.*`
   (`import rsl_rl` became `import mbrl.rl.rsl_rl_fork as rsl_rl`, which keeps
   `rsl_rl.__file__` working for `store_code_state`).

2. Project patches applied in file-name order:

{patches}

Run `python scripts/setup/vendor_rsl_fork.py --source ... --license-file ... --check` to verify
that the checked-in tree is exactly "upstream + rewrite + patches".

The vendored code is imported only by the project's own adapter and scripts; Isaac Lab's
`isaaclab_rl.rsl_rl` keeps importing the host `rsl_rl` 5.5.1.
"""


def rewrite(text: str) -> str:
    """Rewrite absolute ``rsl_rl`` imports into the vendored namespace."""
    lines = []
    for line in text.splitlines(keepends=True):
        stripped = line.rstrip("\r\n")
        plain = PLAIN_IMPORT_RE.match(stripped)
        if plain:
            lines.append(line.replace("import rsl_rl", f"import {PREFIX} as rsl_rl", 1))
            continue
        match = IMPORT_RE.match(stripped)
        if match:
            indent, submodule, names = match.groups()
            lines.append(f"{indent}from {PREFIX}{submodule or ''} import {names}\n")
            continue
        lines.append(line)
    return "".join(lines)


def _relative_files(root: pathlib.Path) -> dict[str, bytes]:
    """Return ``{relative posix path: bytes}`` for every file below *root*."""
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file() and "__pycache__" not in path.parts
    }


def _generate(source: pathlib.Path, license_file: pathlib.Path, patches_dir: pathlib.Path, commit: str) -> pathlib.Path:
    """Build the vendored tree in a temporary directory and return it."""
    temp = pathlib.Path(tempfile.mkdtemp(prefix="rsl_fork_vendor_"))
    try:
        count = 0
        for path in sorted(source.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            target = temp / path.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            text = rewrite(path.read_text(encoding="utf-8"))
            leftover = [line for line in text.splitlines() if LEFTOVER_IMPORT_RE.match(line)]
            if leftover:
                raise SystemExit(f"un-rewritten absolute rsl_rl import in {path}: {leftover}")
            target.write_text(text, encoding="utf-8", newline="")
            count += 1
        shutil.copyfile(license_file, temp / "LICENSE")

        patch_files = sorted(patches_dir.glob("*.patch")) if patches_dir.is_dir() else []
        if not patch_files:
            raise SystemExit(f"no patch files found in {patches_dir}; refusing to vendor without the project patches")
        for patch in patch_files:
            _apply_patch(patch, temp)

        (temp / "NOTICE.md").write_text(
            NOTICE_TEMPLATE.format(
                upstream=UPSTREAM,
                commit=commit,
                patches="\n".join(f"   * `{patch.name}`" for patch in patch_files),
            ),
            encoding="utf-8",
            newline="",
        )

        for path in temp.rglob("*.py"):
            try:
                py_compile.compile(str(path), doraise=True, cfile=str(path) + ".pyc")
            except py_compile.PyCompileError as exc:  # pragma: no cover - defensive
                raise SystemExit(f"vendored module does not compile: {exc}") from exc
            pathlib.Path(str(path) + ".pyc").unlink()
        print(f"prepared {count} modules from {source} (+{len(patch_files)} patches)")
        return temp
    except BaseException:
        shutil.rmtree(temp, ignore_errors=True)
        raise


def _apply_patch(patch: pathlib.Path, root: pathlib.Path) -> None:
    """Apply *patch* (``-p1`` unified diff) inside *root*, failing loudly."""
    result = subprocess.run(
        [
            "git",
            # keep the generated bytes identical to the patch text on Windows hosts
            "-c",
            "core.autocrlf=false",
            "-c",
            "core.eol=lf",
            "apply",
            "--whitespace=nowarn",
            "-p1",
            str(patch.resolve()),
        ],
        cwd=root,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(
            f"patch {patch} does not apply to the vendored tree:\n{result.stderr.strip()}\n"
            "Update the patch series (scripts/setup/rsl_fork_patches) instead of editing the tree by hand."
        )


def _differences(generated: pathlib.Path, dest: pathlib.Path) -> list[str]:
    """Return the relative paths whose content differs between *generated* and *dest*."""
    new = _relative_files(generated)
    old = _relative_files(dest) if dest.is_dir() else {}
    changed = []
    for name in sorted(set(new) | set(old)):
        if new.get(name) != old.get(name):
            changed.append(name)
    return changed


def _describe(generated: pathlib.Path, dest: pathlib.Path, names: list[str], limit: int = 40) -> str:
    lines = []
    for name in names[:limit]:
        lines.append(f"  {'missing in dest' if not (dest / name).is_file() else 'differs'}: {name}")
    if len(names) > limit:
        lines.append(f"  ... ({len(names) - limit} more)")
    return "\n".join(lines)


def _unified_diff(generated: pathlib.Path, dest: pathlib.Path, name: str) -> str:
    new_path = generated / name
    old_path = dest / name
    old = old_path.read_text(encoding="utf-8").splitlines(keepends=True) if old_path.is_file() else []
    new = new_path.read_text(encoding="utf-8").splitlines(keepends=True) if new_path.is_file() else []
    return "".join(
        difflib.unified_diff(old, new, fromfile=f"dest/{name}", tofile=f"generated/{name}")
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", required=True, help="Path to the installed rsl_rl package directory.")
    parser.add_argument("--license-file", required=True, help="Path to the fork's LICENSE file.")
    parser.add_argument("--dest", default=DEFAULT_DEST, help="Destination package directory.")
    parser.add_argument("--patches", default=DEFAULT_PATCHES, help="Directory holding the project patch series.")
    parser.add_argument("--commit", default=PINNED_COMMIT, help="Upstream commit recorded in NOTICE.md.")
    parser.add_argument("--force", action="store_true", help="Replace an existing destination directory.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Only verify that the destination equals a fresh vendoring; exit 1 when it does not.",
    )
    parser.add_argument("--show-diff", action="store_true", help="Print the unified diff for changed files.")
    args = parser.parse_args(argv)

    source = pathlib.Path(args.source)
    dest = pathlib.Path(args.dest)
    patches = pathlib.Path(args.patches)
    license_file = pathlib.Path(args.license_file)
    for path, label in ((source, "source package"), (patches, "patch directory"), (license_file, "license file")):
        if not path.exists():
            raise SystemExit(f"{label} not found: {path}")

    generated = _generate(source, license_file, patches, args.commit)
    try:
        if args.check:
            changed = _differences(generated, dest)
            if changed:
                print(f"CHECK FAILED: {dest} differs from a fresh vendoring in {len(changed)} file(s):")
                print(_describe(generated, dest, changed))
                if args.show_diff:
                    for name in changed:
                        sys.stdout.write(_unified_diff(generated, dest, name))
                return 1
            print(f"CHECK OK: {dest} equals upstream + rewrite + {len(list(patches.glob('*.patch')))} patches")
            return 0

        if dest.exists():
            changed = _differences(generated, dest)
            if not args.force:
                print(f"{dest} already exists; refusing to overwrite {len(changed)} differing file(s):")
                print(_describe(generated, dest, changed))
                print("Re-run with --force to replace it, or with --check to verify it.")
                return 1
            if changed:
                print(f"--force: replacing {dest}; {len(changed)} file(s) differ from the fresh vendoring")
                print(_describe(generated, dest, changed))
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists():
            shutil.rmtree(dest)
        shutil.move(str(generated), str(dest))
        print(f"vendored {dest}")
        return 0
    finally:
        if generated.exists():
            shutil.rmtree(generated, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
